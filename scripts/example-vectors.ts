// Computes, with the packaged model, the vectors of the category examples (lib/data/examples.ts) and stores
// them quantised to 8 bits in lib/data/example-vectors.ts, so that no analysis has to embed them.
// Run after editing the examples: `pnpm examples`.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { env, pipeline } from '@huggingface/transformers';
import { EXAMPLES } from '../lib/data/examples';
import { MODEL_DIMS, MODEL_ID, MODEL_REVISION, modelInput } from '../lib/model';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'lib', 'data', 'example-vectors.ts');
env.allowRemoteModels = false;
env.localModelPath = path.join(ROOT, 'public', 'models') + path.sep;
const extractor = await pipeline('feature-extraction', MODEL_ID, { dtype: 'q8' });

const categories: string[] = [];
const sites: string[] = [];
const bytes: number[] = [];
const scales: number[] = [];
for (const [category, texts] of Object.entries(EXAMPLES)) {
  for (const t of texts) {
    const v = new Float32Array((await extractor(modelInput(t), { pooling: 'mean', normalize: true })).data as Float32Array);
    const scale = Math.max(...v.map(Math.abs)) || 1;
    for (const x of v) bytes.push(Math.round((x / scale) * 127) & 0xff);
    scales.push(Number(scale.toFixed(6)));
    categories.push(category);
    // The site after the dash: an example of YouTube says little about another YouTube page.
    sites.push(t.split(' — ').pop()?.trim().replace(/^(www|open|fr|en)\./, '') ?? '');
  }
}
if (bytes.length !== categories.length * MODEL_DIMS) throw new Error('unexpected vector size');
const body = `// Generated by scripts/example-vectors.ts from lib/data/examples.ts with ${MODEL_ID}@${MODEL_REVISION}. Do not edit.
export const EXAMPLE_MODEL = '${MODEL_ID}@${MODEL_REVISION}';
export const EXAMPLE_CATEGORIES: string[] = ${JSON.stringify(categories)};
export const EXAMPLE_SITES: string[] = ${JSON.stringify(sites)};
export const EXAMPLE_SCALES: number[] = ${JSON.stringify(scales)};
export const EXAMPLE_VECTORS = '${Buffer.from(bytes).toString('base64')}';
`;
fs.writeFileSync(OUT, body);
console.log(`${categories.length} examples written to ${path.relative(ROOT, OUT)} (${Math.round(body.length / 1024)} KB)`);
